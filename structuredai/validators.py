"""Deterministic code & test validators: line cap, placeholders, imports & anti-triche."""

import ast
from pathlib import Path
import re
import sys

from structuredai.config import Config

_PLACEHOLDER_RE = re.compile(r"\b(TODO|FIXME|NotImplementedError)\b|//\s*rest of code|\.\.\.\s*$", re.MULTILINE)
_TRIVIAL_ASSERT_RE = re.compile(r"assert\s+(True|1\s*==\s*1)|expect\(true\)\.toBe\(true\)", re.IGNORECASE)


def check_line_limit(rel_path: str, code: str, cfg: Config) -> str | None:
    """Enforce <= MAX_LINES_PER_FILE unless extension is explicitly exempt."""
    ext = Path(rel_path).suffix.lower()
    if ext in cfg.exempt_exts:
        return None
    count = len(code.splitlines())
    if count > cfg.max_lines_per_file:
        return f"Line limit exceeded: {count} > {cfg.max_lines_per_file} in {rel_path}"
    return None


def check_placeholders(code: str) -> str | None:
    """Reject incomplete stubs or lazy placeholders generated by small models."""
    m = _PLACEHOLDER_RE.search(code)
    if m:
        return f"Placeholder forbidden in code: {m.group(0)!r}"
    return None


def preflight_imports(
    code: str, ext: str, known_local_exports: dict[str, set[str]], installed_pkgs: set[str]
) -> list[str]:
    """Verify local module symbols against REALITY exports and Python stdlib/installed pkgs."""
    if ext != ".py":
        return []
    try:
        tree = ast.parse(code)
    except SyntaxError as exc:
        return [f"SyntaxError line {exc.lineno}: {exc.msg}"]
    errs: list[str] = []
    stdlib = sys.stdlib_module_names
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            root = node.module.split(".")[0]
            mod_rel = node.module.replace(".", "/") + ".py"
            if mod_rel in known_local_exports:
                avail = known_local_exports[mod_rel]
                for alias in node.names:
                    if alias.name != "*" and avail and alias.name not in avail:
                        errs.append(f"Symbol '{alias.name}' not found in '{mod_rel}' (available: {sorted(avail)})")
            elif root not in stdlib and root.lower() not in installed_pkgs and not _looks_local(node.module, known_local_exports):
                errs.append(f"Unknown or uninstalled module '{node.module}'")
    return errs


def _looks_local(mod: str, known: dict[str, set[str]]) -> bool:
    prefix = mod.replace(".", "/")
    return any(k.startswith(prefix) for k in known)


def anti_trivial_test_gate(test_code: str, target_stem: str, ext: str) -> list[str]:
    """Reject assert True, self-mocking, silent excepts, or missing target calls."""
    errs: list[str] = []
    if _TRIVIAL_ASSERT_RE.search(test_code):
        errs.append("Trivial assertion detected (assert True / 1==1)")
    if target_stem not in test_code:
        errs.append(f"Target module '{target_stem}' not imported or referenced in tests")
    if ext == ".py":
        try:
            tree = ast.parse(test_code)
        except SyntaxError as exc:
            return [f"Test SyntaxError line {exc.lineno}: {exc.msg}"]
        asserts = sum(1 for n in ast.walk(tree) if isinstance(n, ast.Assert))
        if asserts < 2 and "pytest.raises" not in test_code and "assertEqual" not in test_code:
            errs.append(f"Need >= 2 meaningful assertions (found {asserts})")
        for n in ast.walk(tree):
            if isinstance(n, ast.ExceptHandler) and len(n.body) == 1 and isinstance(n.body[0], ast.Pass):
                errs.append("Silent 'except: pass' forbidden in tests")
        if re.search(rf"patch\([^)]*{re.escape(target_stem)}", test_code):
            errs.append(f"Self-mocking of target '{target_stem}' forbidden")
    return errs


def check_test_monotonicity(prev_test: str, new_test: str) -> str | None:
    """Prevent deleting or weakening existing assertions during updates."""
    if not prev_test.strip():
        return None
    prev_n = prev_test.count("assert ") + prev_test.count("expect(")
    new_n = new_test.count("assert ") + new_test.count("expect(")
    if new_n < prev_n:
        return f"Test monotonicity violation: assertions dropped {prev_n} -> {new_n}"
    return None
